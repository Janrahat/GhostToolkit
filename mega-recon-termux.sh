#!/data/data/com.termux/files/usr/bin/bash
# =============================================================
# MEGA-RECON-TERMUX.sh  —  Lightweight Recon Toolkit (Termux)
# Usage: bash mega-recon-termux.sh example.com
# WARNING: Use ONLY on targets you are authorized to test.
# =============================================================

TARGET="$1"
[ -z "$TARGET" ] && { echo "Usage: bash $0 <domain>"; exit 1; }

OUT="$TARGET-recon-$(date +%Y%m%d-%H%M%S)"
mkdir -p "$OUT"
T="https://$TARGET"

# ---------- SECTION 1: DEPENDENCY INSTALL (first run only) ----------
echo "════════ [1/5] Installing required packages ════════"
pkg install -y nmap whatweb nikto curl jq 2>/dev/null

# ---------- SECTION 2: RECON ----------
echo "════════ [2/5] Full port scan (-p- : all 65,535 ports) ════════"
# No root on Termux: nmap falls back to full TCP connect scan
nmap -p- -sV -T4 --open "$TARGET" -oN "$OUT/nmap-allports.txt"

echo "════════ [3/5] Technology fingerprint ════════"
whatweb "$T" | tee "$OUT/whatweb.txt"

echo "════════ [4/5] Web server vulnerability scan ════════"
nikto -h "$T" -o "$OUT/nikto.txt" 2>/dev/null

# ---------- SECTION 3: REPORT ----------
echo "════════ [5/5] Generating report ════════"
REPORT="$OUT/REPORT.md"
{
  echo "# Recon Report: $TARGET"
  echo "**Date:** $(date)"
  echo "**Generated by:** mega-recon-termux.sh"
  echo
  echo "## 1. Open Ports (full -p- scan)"
  echo '```'
  grep -E "^[0-9]+/" "$OUT/nmap-allports.txt" 2>/dev/null | head -40
  echo '```'
  echo "## 2. Technologies Detected"
  echo '```'
  cat "$OUT/whatweb.txt" 2>/dev/null
  echo '```'
  echo "## 3. Nikto Findings"
  echo '```'
  head -60 "$OUT/nikto.txt" 2>/dev/null
  echo '```'
} > "$REPORT"

echo "════════ DONE ════════"
echo "[+] All results saved in: $OUT/"
echo "[+] Full report: $REPORT"
