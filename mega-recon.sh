#!/bin/bash
# =============================================================
# MEGA-RECON.sh  —  All-in-One Recon Toolkit (Kali Linux)
# Usage: ./mega-recon.sh example.com
# WARNING: Use ONLY on targets you are authorized to test.
# =============================================================

TARGET="$1"
[ -z "$TARGET" ] && { echo "Usage: ./mega-recon.sh <domain>"; exit 1; }

OUT="$TARGET-recon-$(date +%Y%m%d-%H%M%S)"
mkdir -p "$OUT"
T="https://$TARGET"

# ---------- SECTION 1: DEPENDENCY CHECK & INSTALL ----------
echo "════════ [1/8] Checking & installing tools ════════"
TOOLS="nmap whatweb nikto gobuster subfinder wafw00f curl jq"
for tool in $TOOLS; do
  command -v "$tool" >/dev/null 2>&1 || {
    echo "[+] Installing: $tool"
    sudo apt install -y "$tool" >/dev/null 2>&1 || echo "[!] Failed: $tool"
  }
done

# Go tools if missing
export PATH="$PATH:$HOME/go/bin"
command -v waybackurls >/dev/null 2>&1 || go install github.com/tomnomnom/waybackurls@latest

WLIST="/usr/share/wordlists/dirb/common.txt"
[ -f "$WLIST" ] || sudo apt install -y dirb

# ---------- SECTION 2: RECON ----------
echo "════════ [2/8] Subdomain enumeration ════════"
subfinder -d "$TARGET" -silent | tee "$OUT/subdomains.txt" | wc -l

echo "════════ [3/8] Full port scan (-p- : all 65,535 ports) ════════"
sudo nmap -p- -sV -T4 --open "$TARGET" -oN "$OUT/nmap-allports.txt"
OPEN_PORTS="$(grep -oE '^[0-9]+/' "$OUT/nmap-allports.txt" | tr -d '/' | paste -sd,)"
if [ -n "$OPEN_PORTS" ]; then
  sudo nmap -sC -sV -p "$OPEN_PORTS" "$TARGET" -oN "$OUT/nmap-service-scan.txt"
fi

echo "════════ [4/8] Technology fingerprint ════════"
whatweb "$T" -a 3 | tee "$OUT/whatweb.txt"

echo "════════ [5/8] WAF detection ════════"
wafw00f "$T" | tee "$OUT/waf.txt"

echo "════════ [6/8] Historical URLs (Wayback) ════════"
waybackurls "$TARGET" | tee "$OUT/urls.txt" | wc -l

echo "════════ [7/8] Directory brute-force ════════"
gobuster dir -u "$T" -w "$WLIST" -t 30 -o "$OUT/directories.txt" 2>/dev/null

echo "════════ [8/8] Web server vulnerability scan ════════"
nikto -h "$T" -o "$OUT/nikto.txt" 2>/dev/null

# ---------- SECTION 3: REPORT ----------
REPORT="$OUT/REPORT.md"
{
  echo "# Recon Report: $TARGET"
  echo "**Date:** $(date)"
  echo "**Generated by:** mega-recon.sh"
  echo
  echo "## 1. Subdomains"
  echo "Total found: $(wc -l < "$OUT/subdomains.txt" 2>/dev/null || echo 0)"
  echo '```'
  head -30 "$OUT/subdomains.txt" 2>/dev/null
  echo '```'
  echo "## 2. Open Ports (full -p- scan)"
  echo '```'
  grep -E "^[0-9]+/" "$OUT/nmap-allports.txt" 2>/dev/null | head -40
  echo '```'
  echo "## 3. Service & Script Scan"
  echo '```'
  head -60 "$OUT/nmap-service-scan.txt" 2>/dev/null
  echo '```'
  echo "## 4. Technologies Detected"
  echo '```'
  cat "$OUT/whatweb.txt" 2>/dev/null
  echo '```'
  echo "## 5. WAF"
  echo '```'
  cat "$OUT/waf.txt" 2>/dev/null
  echo '```'
  echo "## 6. Directories Found"
  echo '```'
  head -50 "$OUT/directories.txt" 2>/dev/null
  echo '```'
  echo "## 7. Nikto Findings"
  echo '```'
  head -60 "$OUT/nikto.txt" 2>/dev/null
  echo '```'
} > "$REPORT"

echo "════════ DONE ════════"
echo "[+] All results saved in: $OUT/"
echo "[+] Full report: $REPORT"
